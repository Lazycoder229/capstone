"use client"

import { useEffect, useRef, useState } from "react"
import {
  Calculator,
  Clock3,
  Download,
  History,
  Trash2,
  Wallet,
} from "lucide-react"
import { Button } from "@/components/ui/button"
import { Card, CardContent } from "@/components/ui/card"
import { usePayroll } from "./hooks/use-payroll"
import type { PayrollPeriodRow } from "./types"
import type { PayrollCalculationSettings } from "@/lib/payroll/settings"

const money = (amount: number) =>
  `₱${amount.toLocaleString("en-PH", { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`

function formatHours(hours: number) {
  const totalMinutes = Math.max(0, Math.round(hours * 60))
  const wholeHours = Math.floor(totalMinutes / 60)
  const minutes = totalMinutes % 60
  if (!wholeHours) return `${minutes}m`
  if (!minutes) return `${wholeHours}h`
  return `${wholeHours}h ${minutes}m`
}

function cutoffFor(month: string, payday: "5" | "20") {
  const [year, monthNumber] = month.split("-").map(Number)
  if (!year || !monthNumber) return null
  if (payday === "20") return { start: `${month}-01`, end: `${month}-15` }
  const previous = new Date(Date.UTC(year, monthNumber - 2, 1))
  const previousMonth = `${previous.getUTCFullYear()}-${String(previous.getUTCMonth() + 1).padStart(2, "0")}`
  const lastDay = new Date(Date.UTC(year, monthNumber - 1, 0)).getUTCDate()
  return {
    start: `${previousMonth}-16`,
    end: `${previousMonth}-${String(lastDay).padStart(2, "0")}`,
  }
}

function defaultPayoutSelection(date = new Date()) {
  const payoutDate = new Date(date.getFullYear(), date.getMonth(), 1)
  if (date.getDate() > 15) payoutDate.setMonth(payoutDate.getMonth() + 1)
  return {
    month: `${payoutDate.getFullYear()}-${String(payoutDate.getMonth() + 1).padStart(2, "0")}`,
    payday: (date.getDate() <= 15 ? "20" : "5") as "5" | "20",
  }
}

function localDateKey(date: Date) {
  return `${date.getFullYear()}-${String(date.getMonth() + 1).padStart(2, "0")}-${String(date.getDate()).padStart(2, "0")}`
}

export function PayrollWorkspace({
  periods,
  calculationSettings,
}: {
  periods: PayrollPeriodRow[]
  calculationSettings: PayrollCalculationSettings
}) {
  const [initialPayout] = useState(defaultPayoutSelection)
  const [month, setMonth] = useState(initialPayout.month)
  const [payday, setPayday] = useState<"5" | "20">(initialPayout.payday)
  const [view, setView] = useState<"active" | "history">("active")
  const [todayKey, setTodayKey] = useState(() => localDateKey(new Date()))
  const selectionTouched = useRef(false)
  const autoGenerated = useRef(new Set<string>())
  const { pending, generate, close, remove } = usePayroll()
  const activePeriods = periods.filter((period) => period.status !== "closed")
  const historyPeriods = periods.filter((period) => period.status === "closed")
  const visiblePeriods = view === "active" ? activePeriods : historyPeriods
  const records = activePeriods.flatMap((period) => period.records)
  const latestGross = records.reduce((sum, row) => sum + row.grossPay, 0)
  const latestNet = records.reduce((sum, row) => sum + row.netPay, 0)

  useEffect(() => {
    const timer = window.setInterval(() => {
      const now = new Date()
      const nextTodayKey = localDateKey(now)
      setTodayKey((current) =>
        current === nextTodayKey ? current : nextTodayKey
      )
      if (!selectionTouched.current) {
        const nextSelection = defaultPayoutSelection(now)
        setMonth((current) =>
          current === nextSelection.month ? current : nextSelection.month
        )
        setPayday((current) =>
          current === nextSelection.payday ? current : nextSelection.payday
        )
      }
    }, 60_000)
    return () => window.clearInterval(timer)
  }, [])

  useEffect(() => {
    const cutoff = cutoffFor(month, payday)
    const cutoffEndKey = cutoff?.end === todayKey ? todayKey : ""
    const key = `${month}:${payday}:${cutoffEndKey}`
    if (
      !/^\d{4}-(0[1-9]|1[0-2])$/.test(month) ||
      autoGenerated.current.has(key)
    )
      return
    autoGenerated.current.add(key)
    if (
      cutoff &&
      periods.some(
        (period) =>
          period.periodStart === cutoff.start &&
          period.periodEnd === cutoff.end &&
          period.status === "closed"
      )
    )
      return
    generate(month, payday, true)
  }, [generate, month, payday, periods, todayKey])

  return (
    <main className="space-y-4">
      <header>
        <h1 className="text-2xl font-semibold tracking-tight">Payroll</h1>
        <p className="text-sm text-muted-foreground">
          Active payroll updates automatically for the selected cutoff. Paydays:
          5th (cutoff 16–end of prior month) and 20th (cutoff 1–15). Rules:{" "}
          {calculationSettings.payrollDutyHours} paid h/shift,{" "}
          {calculationSettings.payrollUnpaidBreakHours} unpaid break h,{" "}
          {calculationSettings.payrollWorkdaysPerMonth} workdays/month, and{" "}
          {calculationSettings.payrollOvertimeMultiplier}× overtime. Configure
          in System Settings → Payroll.
        </p>
      </header>
      <div className="grid gap-3 sm:grid-cols-3">
        <Summary
          label="Active payroll records"
          value={records.length}
          icon={Wallet}
        />
        <Summary
          label="Active gross"
          value={money(latestGross)}
          icon={Calculator}
        />
        <Summary label="Active net" value={money(latestNet)} icon={Clock3} />
      </div>
      <Card size="sm" className="[--card-spacing:--spacing(0)]">
        <CardContent className="p-3">
          <div className="flex flex-wrap items-end gap-2">
            <label className="grid gap-1 text-xs font-medium text-muted-foreground">
              Payout month
              <input
                type="month"
                value={month}
                onChange={(event) => {
                  selectionTouched.current = true
                  setMonth(event.target.value)
                }}
                className="h-8 rounded-md border bg-background px-2.5 text-sm text-foreground"
              />
            </label>
            <label className="grid gap-1 text-xs font-medium text-muted-foreground">
              Payday
              <select
                value={payday}
                onChange={(event) => {
                  selectionTouched.current = true
                  setPayday(event.target.value as "5" | "20")
                }}
                className="h-8 rounded-md border bg-background px-2.5 text-sm text-foreground"
              >
                <option value="20">20th — cutoff 1–15</option>
                <option value="5">5th — cutoff 16–end of prior month</option>
              </select>
            </label>
            <Button
              disabled={pending || !month}
              onClick={() => generate(month, payday)}
            >
              <Calculator className="mr-1.5 size-4" />
              {pending ? "Calculating…" : "Recalculate payroll"}
            </Button>
          </div>
        </CardContent>
      </Card>

      <div className="space-y-3">
        <nav
          aria-label="Payroll periods"
          className="flex w-fit gap-1 rounded-lg border bg-muted/40 p-1"
        >
          <button
            type="button"
            aria-pressed={view === "active"}
            onClick={() => setView("active")}
            className={`rounded-md px-3 py-1.5 text-sm ${view === "active" ? "bg-background font-medium shadow-sm" : "text-muted-foreground hover:text-foreground"}`}
          >
            Active <span className="ml-1 text-xs">{activePeriods.length}</span>
          </button>
          <button
            type="button"
            aria-pressed={view === "history"}
            onClick={() => setView("history")}
            className={`inline-flex items-center gap-1.5 rounded-md px-3 py-1.5 text-sm ${view === "history" ? "bg-background font-medium shadow-sm" : "text-muted-foreground hover:text-foreground"}`}
          >
            <History className="size-3.5" /> History
            <span className="ml-1 text-xs">{historyPeriods.length}</span>
          </button>
        </nav>
        {visiblePeriods.map((period) => (
          <Card key={period.id} className="overflow-hidden p-0">
            <div className="flex flex-wrap items-center justify-between gap-2 border-b bg-muted/20 px-4 py-3">
              <div>
                <h2 className="font-semibold">
                  Cutoff {period.periodStart} to {period.periodEnd}
                </h2>
                <p className="text-xs text-muted-foreground">
                  {period.records.length} employee record(s)
                </p>
              </div>
              <div className="flex items-center gap-2">
                {period.status !== "closed" ? (
                  <Button
                    size="icon"
                    variant="ghost"
                    aria-label={`Delete payroll ${period.periodStart} to ${period.periodEnd}`}
                    disabled={pending}
                    onClick={() =>
                      void remove(
                        period.id,
                        `${period.periodStart} to ${period.periodEnd}`
                      )
                    }
                  >
                    <Trash2 className="size-4 text-destructive" />
                  </Button>
                ) : null}
                {period.records.length ? (
                  <Button
                    size="sm"
                    variant="outline"
                    onClick={() =>
                      window.location.assign(
                        `/admin/payroll/${period.id}/payslips`
                      )
                    }
                  >
                    <Download className="mr-1.5 size-4" />
                    Download payslips
                  </Button>
                ) : null}
                <span className="rounded-full bg-muted px-2.5 py-1 text-xs capitalize">
                  {period.status}
                </span>
                {period.status !== "closed" && period.records.length ? (
                  <Button
                    size="sm"
                    variant="outline"
                    disabled={pending}
                    onClick={() =>
                      void close(
                        period.id,
                        `${period.periodStart} to ${period.periodEnd}`
                      )
                    }
                  >
                    Close &amp; lock
                  </Button>
                ) : null}
              </div>
            </div>
            <div className="overflow-x-auto">
              <table className="w-full min-w-[900px] text-sm">
                <thead className="border-b text-left text-xs text-muted-foreground">
                  <tr>
                    {[
                      "Employee",
                      "Time worked",
                      "Gross",
                      "Employee deductions",
                      "Net pay",
                      "Employer shares",
                    ].map((label) => (
                      <th key={label} className="px-4 py-3 font-medium">
                        {label}
                      </th>
                    ))}
                  </tr>
                </thead>
                <tbody className="divide-y">
                  {period.records.map((record) => (
                    <tr key={record.id} className="align-top">
                      <td className="px-4 py-3">
                        <div className="font-medium">{record.employeeName}</div>
                        <div className="text-xs text-muted-foreground">
                          {record.employeeNumber}
                        </div>
                        <div className="text-xs text-muted-foreground">
                          {money(record.dailyRate)} / day
                        </div>
                      </td>
                      <td className="min-w-[170px] px-4 py-3">
                        <div className="flex items-center justify-between gap-3">
                          <span className="font-medium">
                            {formatHours(record.paidHours)} worked
                          </span>
                          <span className="text-xs text-muted-foreground tabular-nums">
                            {Math.min(
                              100,
                              Math.round(
                                (record.paidHours /
                                  calculationSettings.payrollDutyHours) *
                                  100
                              )
                            )}
                            %
                          </span>
                        </div>
                        <div
                          role="progressbar"
                          aria-label="Paid hours in a workday"
                          aria-valuemin={0}
                          aria-valuemax={calculationSettings.payrollDutyHours}
                          aria-valuenow={Math.min(
                            record.paidHours,
                            calculationSettings.payrollDutyHours
                          )}
                          className="mt-1.5 h-1.5 overflow-hidden rounded-full bg-muted"
                        >
                          <div
                            className="h-full rounded-full bg-primary"
                            style={{
                              width: `${Math.min(100, Math.max(0, (record.paidHours / calculationSettings.payrollDutyHours) * 100))}%`,
                            }}
                          />
                        </div>
                        <div className="mt-1 text-xs text-muted-foreground">
                          of {calculationSettings.payrollDutyHours} paid-hour
                          shift
                        </div>
                        {record.overtimeHours > 0 ? (
                          <div className="text-xs text-muted-foreground">
                            + {formatHours(record.overtimeHours)} overtime
                          </div>
                        ) : null}
                      </td>
                      <td className="px-4 py-3 tabular-nums">
                        {money(record.grossPay)}
                      </td>
                      <td className="px-4 py-3">
                        {record.deductions.map((item) => (
                          <div
                            key={item.name}
                            className="flex justify-between gap-4"
                          >
                            <span>{item.name}</span>
                            <span className="tabular-nums">
                              {money(item.amount)}
                            </span>
                          </div>
                        ))}
                        <div className="mt-1 flex justify-between border-t pt-1 font-medium">
                          <span>Total</span>
                          <span>{money(record.totalDeductions)}</span>
                        </div>
                      </td>
                      <td className="px-4 py-3 font-semibold tabular-nums">
                        {money(record.netPay)}
                      </td>
                      <td className="px-4 py-3">
                        {record.deductions.map((item) => (
                          <div
                            key={item.name}
                            className="flex justify-between gap-4"
                          >
                            <span>
                              {item.name.replace("employee share", "")}
                            </span>
                            <span className="tabular-nums">
                              {money(item.employerAmount)}
                            </span>
                          </div>
                        ))}
                      </td>
                    </tr>
                  ))}
                  {!period.records.length ? (
                    <tr>
                      <td
                        colSpan={6}
                        className="px-4 py-8 text-center text-muted-foreground"
                      >
                        No payroll records in this cutoff.
                      </td>
                    </tr>
                  ) : null}
                </tbody>
              </table>
            </div>
          </Card>
        ))}
        {!visiblePeriods.length ? (
          <Card size="sm">
            <CardContent className="p-4 text-center text-sm text-muted-foreground">
              {view === "active"
                ? "No active payroll. Generate payroll for a cutoff to begin."
                : "Closed payroll periods will appear in history."}
            </CardContent>
          </Card>
        ) : null}
      </div>
    </main>
  )
}

function Summary({
  label,
  value,
  icon: Icon,
}: {
  label: string
  value: string | number
  icon: typeof Wallet
}) {
  return (
    <Card size="sm" className="[--card-spacing:--spacing(0)]">
      <CardContent className="p-2.5">
        <div className="flex items-center gap-2.5">
          <span className="rounded-md bg-muted p-1.5">
            <Icon className="size-3.5" />
          </span>
          <div className="min-w-0">
            <div className="text-xs text-muted-foreground">{label}</div>
            <div className="truncate text-lg font-semibold tabular-nums">
              {value}
            </div>
          </div>
        </div>
      </CardContent>
    </Card>
  )
}
